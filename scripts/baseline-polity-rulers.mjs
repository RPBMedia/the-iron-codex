/**
 * Records, per polity, how many of its own rulers its page fails to name.
 *
 * Shrink-only, like the template-prose and vague-caption baselines: the gate in
 * check-content-quality.mjs fails if a count GROWS, and fails as stale if a
 * count shrinks without this being regenerated. So the debt can only go down.
 *
 * Why a baseline rather than "name them all": these are curated "Major rulers"
 * sections, not indexes. Denmark naming 4 of 25 is plainly wrong; Wessex naming
 * 4 of 6 may be right editorial judgement. A gate demanding completeness would
 * force padding, which the no-filler rules forbid. A gate demanding "no worse
 * than today" catches the real failure — a ruler article appearing and its realm
 * never mentioning it, which is exactly what happened with Eric the Victorious.
 *
 * Usage: node scripts/baseline-polity-rulers.mjs
 */
import fs from 'node:fs'
import { loadArchive } from '../server/data/archive.mjs'
import { coverageFor, isPolity } from './lib/polity-ruler-coverage.mjs'

const data = loadArchive()
const out = {}

for (const location of data.locations ?? []) {
  if (!isPolity(location)) continue
  const { total, missing } = coverageFor(location, data)
  if (!total || !missing.length) continue
  out[location.id] = {
    missing: missing.length,
    of: total,
    names: missing.map((m) => m.name).sort()
  }
}

const path = new URL('./lib/polity-ruler-baseline.json', import.meta.url)
const payload = {
  note:
    'Rulers who have articles but are not named on the page of the realm they ruled. ' +
    'Shrink-only: check-content-quality.mjs fails if any count grows, and fails as stale if one shrinks ' +
    'without regenerating this file. Generated by scripts/baseline-polity-rulers.mjs.',
  generated: new Date().toISOString().slice(0, 10),
  polities: out
}
fs.writeFileSync(path, JSON.stringify(payload, null, 2) + '\n')

const totalMissing = Object.values(out).reduce((n, p) => n + p.missing, 0)
console.log(`polity-ruler baseline: ${Object.keys(out).length} polities, ${totalMissing} unnamed rulers`)
for (const [id, p] of Object.entries(out).sort((a, b) => b[1].missing - a[1].missing)) {
  console.log(`  ${String(p.missing).padStart(2)}/${String(p.of).padEnd(3)} ${id}`)
}
